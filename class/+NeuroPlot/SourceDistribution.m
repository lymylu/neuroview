     function calculateSourceDistribution(obj)
            % 计算源分布         
            if isempty(obj.Data) || isempty(obj.ChannelPosition)
                error('没有可用的数据或通道位置信息');
            end 
            try
                obj.ChooseDatatype();
            end
            xlim=findobj(obj,'Tag','dataXlim');
            xlim=str2num(xlim.String);
            if ~isempty(obj.dataYaxis)
                ylim=findobj(obj,'Tag','dataYlim');
                ylim=str2num(ylim.String);
                data=squeeze(mean(obj.Data(obj.dataXaxis>=xlim(1)&obj.dataXaxis<=xlim(2),obj.dataYaxis>ylim(1)&obj.dataYaxis<ylim(2),:,:),[2,4]));
            else
                data=squeeze(mean(obj.Data(obj.dataXaxis>=xlim(1)&obj.dataXaxis<=xlim(2),:,:),3));
            end
            parameters=obj.Parameters;
            delete(findobj('Parent',obj.figurepanel));
            switch obj.ChannelType
                case 'CSD'
                    obj.Source=obj.calculateCSD(data,parameters);
                    if isfield(obj.Source,'csd_x')&& isfield(obj.Source,'csd_y') 
                        obj.figurepanel.create([],'SourceDistribution','imagesc3D');
                        obj.figurepanel.plot(obj.dataXaxis,obj.Source.csd_x(1,:),obj.Source.csd_y(:,1),obj.Source.CSD);
                    elseif isfield(obj.Source,'csd_x')
                        obj.figurepanel.create([],'SourceDistribution','imagesc-scroll');
                        obj.figurepanel.plot(obj.dataXaxis,obj.Source.csd_x,obj.Source.CSD);
                    elseif isfield(obj.Source,'csd_y')
                        obj.figurepanel.create([],'SourceDistribution','imagesc-scroll');
                        obj.figurepanel.plot(obj.dataXaxis,obj.Source.csd_y,obj.Source.CSD);
                    end
                case 'EEG'
                    [~, sourcedata,grid,xmesh,ymesh]=obj.calculateTopo(data,parameters);
                    obj.Source=sourcedata;
                    obj.grid=grid;
                    obj.xmesh=xmesh;
                    obj.ymesh=ymesh;
            end
     end
