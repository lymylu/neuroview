     function createToolbar(obj)
            if ~isempty(obj.Toolbar) && ishandle(obj.Toolbar)
                delete(obj.Toolbar);
            end
            obj.Toolbar = uix.HBox('Parent', obj);
            switch obj.ChannelType
                case 'EEG'
                uicontrol(obj.Toolbar,"Style","pushbutton","String",'setTopoplotParameter','Callback',@(~,~) obj.openEEGParameters());
                uicontrol(obj.Toolbar,'Style','pushbutton','String','CalculateTopoplot','Callback',obj.calculateSourceDistribution);
                case 'CSD'
                uicontrol(obj.Toolbar,"Style","pushbutton","String",'setCSDParameter','Callback',@(~,~) obj.openCSDParameters());
                uicontrol(obj.Toolbar,'Style','pushbutton','String','CalculateTopoplot','Callback',@(~,~) obj.calculateSourceDistribution);
            end
     end
     function createDataLoadPanel(obj)
            global currentresult
            validdatatype={'LFPdata','Spectrogram','TimeVaringConnectivity','PowerSpectralDensity','Connectivity'};
            datatypelist=[];
            for i=1:length(validdatatype)
                if isprop(currentresult,validdatatype{i})
                datatypelist=cat(1,datatypelist,validdatatype(i));
                end
            end
            if ~isempty(datatypelist)
            uicontrol(obj,"Tag",'Datatype',"Style","popupmenu","String",datatypelist,'Callback',@(~,~) obj.ChooseDatatype);
            else
                error('No support data to calculate source distribution');
            end
     end
     function ChooseDatatype(obj)
         global currentresult
         datatype=findobj(obj,'Tag','Datatype');
         datatype=datatype.String{datatype.Value};
         axisdefine=obj.Toolbar;
         delete(findobj(axisdefine,'style','text'));
         delete(findobj(axisdefine,'style','edit'));
         switch datatype
             case 'LFPdata'
                 uicontrol(axisdefine,"Style",'text','String','time range');
                 uicontrol(axisdefine,'Style','edit','Tag','dataXlim');
                 obj.LoadData('LFPdata');
             case 'Spectrogram'
                 uicontrol(axisdefine,"Style",'text','String','time range');
                 uicontrol(axisdefine,'Style','edit','Tag','dataXlim');
                 uicontrol(axisdefine,"Style",'text','String','frequency range');
                 uicontrol(axisdefine,'Style','edit','Tag','dataYlim');
                 obj.LoadData('Specdata');
                 % further data type are not working!
         end
     end
     function LoadData(obj,option)
         global currentresult
         switch option
             case 'LFPdata'
                obj.Data=currentresult.get('LFPdataplot');
                obj.dataXaxis=currentresult.get('t_lfpplot');
                tmp=findobj('Tag','dataXlim');
                tmp.String=num2str([min(obj.dataXaxis),max(obj.dataXaxis)]);
                obj.dataYaxis=[];
                ChannelPositionindex=currentresult.get('channelindexplot');
             case 'Specdata'
                obj.Data=currentresult.Spectrogram.get('Specdataplot');
                obj.dataXaxis=currentresult.Spectrogram.get('t_lfpplot');
                obj.dataYaxis=currentresult.Spectrogram.get('f_lfpplot');
                tmp=findobj('Tag','dataXlim');
                tmp.String=num2str([min(obj.dataXaxis),max(obj.dataXaxis)]);
                tmp=findobj('Tag','dataYlim');
                tmp.String=num2str([min(obj.dataYaxis),max(obj.dataYaxis)]);
                ChannelPositionindex=currentresult.Spectrogram.get('channelindexplot');
         end
         [~,Channelindex]=ismember(currentresult.LFPinfo.channelselect(ChannelPositionindex),obj.ChannelPosition(:,1));
         obj.ChannelPosition=obj.ChannelPosition(Channelindex,:);
     end
