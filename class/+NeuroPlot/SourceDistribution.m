methods(Static)
    function obj=create(parent,varargin)
            % create a panel in the parent from a neuroresult
           if isempty(parent)
                parent=figure;
            end
            p=inputParser;
            addParameter(p,'Data',[],@isnumeric);% 2-D ,with 1-D as position;
            addParameter(p,'ChannelPosition',[],@(x) isstruct(x)||@(x) isnumeric(x));
            parse(p);
            if isempty(p.Results.ChannelPosition)
                global currentresult
                if isfield(currentresult.ChannelTag,'ChannelPosition')
                    ChannelPosition=currentresult.ChannelTag.ChannelPosition;
                else
                    error('No channel position was detected!');
                end
            end
            obj=NeuroPlot.SourceDistribution('Parent',parent);
            
            if isstruct(ChannelPosition) % EEG format
                obj.ChannelType='EEG';
                obj.Parameters=obj.DEFAULT_EEG_PARAMS;
                obj.ChannelPosition=ChannelPosition;% not worked yet, string should be char.
                   
            else % channelindex,channelposition(x,y),channelshank
                obj.ChannelType='CSD';
                obj.Parameters=obj.DEFAULT_CSD_PARAMS;
                obj.ChannelPosition=ChannelPosition;
                           
            end
            obj.createToolbar();
            if isempty(p.Results.Data)
                warning('load Data from the panel');
                obj.createDataLoadPanel();
            else
                obj.Data=Data;
            end
            obj.figurepanel=NeuroPlot.figurecontrol('Parent',obj);
           
            set(obj,'Heights',[-1,-1,-8]);
            
    end
    
